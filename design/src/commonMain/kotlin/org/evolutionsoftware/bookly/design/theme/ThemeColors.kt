package org.evolutionsoftware.bookly.design.theme

import androidx.compose.material3.ColorScheme
import androidx.compose.material3.darkColorScheme
import androidx.compose.material3.lightColorScheme
import androidx.compose.ui.graphics.Color

data class ThemeColors(
    val bgBase: Color,
    val bgSurface: Color,
    val bgElevated: Color,
    val bgAccent: Color,
    val bgAccentPressed: Color,
    val bgAccentSoft: Color,
    val bgAccentStrong: Color,
    val bgSuccessSoft: Color,
    val bgInfoSoft: Color,
    val bgWarningSoft: Color,
    val bgDangerSoft: Color,
    val text: Color,
    val textMuted: Color,
    val textSubtle: Color,
    val textInverse: Color,
    val textAccent: Color,
    val textBrand: Color,
    val textSuccess: Color,
    val textDanger: Color,
    val textInfo: Color,
    val border: Color,
    val borderAccent: Color,
    val bgDisabled: Color,
    val bgDisabledBase: Color,
    val success: Color,
    val warning: Color,
    val favorite: Color,
    val shadowSoft: Color,
    val shadowStrong: Color,
    val socialGoogle: Color,
    val socialFacebook: Color,
    val bgPrimaryButton: Color = bgAccent,
    val bgPrimaryButtonPressed: Color = bgAccentPressed,
    val textPrimaryButton: Color = textInverse,
    val bgSecondaryButton: Color = text,
    val textSecondaryButton: Color = textInverse,
    val textInput: Color = text,
)

fun ThemeColors.toMaterialColors(darkTheme: Boolean): ColorScheme =
    (if (darkTheme) darkColorScheme() else lightColorScheme()).copy(
        surface = bgSurface,
        background = bgBase,
        onBackground = text,
        onSurface = text,
        primary = textAccent,
        onPrimary = textInverse,
        primaryContainer = bgAccentSoft,
        onPrimaryContainer = textAccent,
        secondary = textAccent,
        onSecondary = textInverse,
        secondaryContainer = bgElevated,
        onSecondaryContainer = textMuted,
        tertiary = textInfo,
        onTertiary = textInverse,
        tertiaryContainer = bgInfoSoft,
        onTertiaryContainer = textInfo,
        surfaceVariant = bgElevated,
        onSurfaceVariant = textMuted,
        surfaceTint = bgAccent,
        surfaceDim = bgElevated,
        surfaceBright = bgSurface,
        surfaceContainerLowest = bgBase,
        surfaceContainerLow = bgSurface,
        surfaceContainer = bgSurface,
        surfaceContainerHigh = bgElevated,
        surfaceContainerHighest = bgElevated,
        outline = borderAccent,
        outlineVariant = border,
        error = textDanger,
        onError = textInverse,
        errorContainer = bgDangerSoft,
        onErrorContainer = textDanger,
        inverseSurface = textAccent,
        inverseOnSurface = bgSurface,
        inversePrimary = bgAccentSoft,
    )
